package com.mrarron.wristclaude.core

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonNull
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import kotlinx.serialization.json.long
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test
import java.time.Instant
import java.time.ZoneId
import java.time.ZonedDateTime

/**
 * Golden vectors generated by running the watch project's src/pkjs/text.js and claude.js under Node
 * (TZ=America/New_York and TZ=Australia/Lord_Howe). The Kotlin port must give identical output.
 */
class GoldenTest {
    private fun load(name: String): JsonObject =
        Json.parseToJsonElement(javaClass.getResource("/$name")!!.readText()).jsonObject

    private val ny = load("golden_ny.json")

    private fun s(e: Any?) = (e as JsonPrimitive).content

    @Test
    fun sanitizeMatchesJs() {
        val cases = ny["sanitize"]!!.jsonArray
        assertTrue(cases.size > 15)
        for (c in cases) {
            val a = c.jsonArray
            assertEquals("sanitize(${s(a[0])})", s(a[1]), TextUtil.sanitize(s(a[0])))
        }
    }

    @Test
    fun truncateMatchesJs() {
        for (c in ny["truncate"]!!.jsonArray) {
            val a = c.jsonArray
            assertEquals(s(a[2]), TextUtil.truncateBytes(s(a[0]), a[1].jsonPrimitive.int))
        }
    }

    @Test
    fun chunkMatchesJs() {
        for (c in ny["chunk"]!!.jsonArray) {
            val a = c.jsonArray
            val expected = a[2].jsonArray.map { s(it) }
            assertEquals(expected, TextUtil.chunk(s(a[0]), a[1].jsonPrimitive.int))
        }
    }

    @Test
    fun watchPipelineMatchesJs() {
        for (c in ny["watch"]!!.jsonArray) {
            val a = c.jsonArray
            val expected = a[1].jsonArray.map { s(it) }
            val got = TextUtil.watchChunks(TextUtil.sanitize(s(a[0])))
            assertEquals(expected, got)
            got.forEach { assertTrue(TextUtil.utf8Bytes(it) <= TextUtil.CHUNK_BYTES) }
            assertTrue(TextUtil.utf8Bytes(got.joinToString("")) <= TextUtil.MAX_ANSWER_BYTES)
        }
    }

    @Test
    fun sanitizeOutputIsLatin1Only() {
        for (c in ny["sanitize"]!!.jsonArray) {
            val out = TextUtil.sanitize(s(c.jsonArray[0]))
            out.forEach { ch -> assertTrue("char ${ch.code}", ch == '\n' || ch == '\t' || ch.code in 0x20..0x7E || ch.code in 0xA1..0xFF) }
        }
    }

    private fun runReminders(golden: JsonObject, zone: ZoneId) {
        val now = ZonedDateTime.ofInstant(Instant.ofEpochSecond(golden["nowEpoch"]!!.jsonPrimitive.long), zone)
        for (c in golden["reminder"]!!.jsonArray) {
            val a = c.jsonArray
            val input = a[0].jsonObject
            val mins: Any? = (input["minutes_from_now"] as? JsonPrimitive)?.let { if (it.isString) it.content else it.content.toDouble() }
            val at = (input["at_local_time"] as? JsonPrimitive)?.content
            val t = TimeUtil.reminderTime(mins, at, now)
            if (a[1] is JsonNull) {
                assertNull("input $input", t)
            } else {
                assertEquals("input $input", a[1].jsonPrimitive.long, t)
                assertEquals("format $input", s(a[2]), TimeUtil.formatReminder(t!!, now))
            }
        }
    }

    @Test
    fun reminderTimeMatchesJs() = runReminders(ny, ZoneId.of("America/New_York"))

    @Test
    fun reminderTimeAcrossDstGapMatchesJs() = runReminders(load("golden_lh.json"), ZoneId.of("Australia/Lord_Howe"))

    @Test
    fun nowLineMatchesJsPromptLine() {
        val now = ZonedDateTime.ofInstant(Instant.ofEpochSecond(ny["nowEpoch"]!!.jsonPrimitive.long), ZoneId.of("America/New_York"))
        assertEquals(s(ny["prompt"]), "Current local date and time: ${TimeUtil.nowLine(now)}.")
    }

    @Suppress("unused")
    private fun JsonArray.strings() = map { s(it) }
}
